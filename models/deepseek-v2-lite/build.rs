// Transcribes this directory's config.json into `$OUT_DIR/config_consts.rs`.
// A dumb copy: numbers are copied, never derived. Derived values live in
// src/lib.rs next to a comment saying how.
use std::{env, fs, path::Path};

const KEYS: &[(&str, &str, &str)] = &[
    ("hidden_size", "HIDDEN_SIZE", "usize"),
    ("intermediate_size", "INTERMEDIATE_SIZE", "usize"),
    ("moe_intermediate_size", "MOE_INTERMEDIATE_SIZE", "usize"),
    ("n_routed_experts", "N_ROUTED_EXPERTS", "usize"),
    ("n_shared_experts", "N_SHARED_EXPERTS", "usize"),
    ("num_experts_per_tok", "NUM_EXPERTS_PER_TOK", "usize"),
    ("num_hidden_layers", "NUM_HIDDEN_LAYERS", "usize"),
    ("first_k_dense_replace", "FIRST_K_DENSE_REPLACE", "usize"),
    ("num_attention_heads", "NUM_ATTENTION_HEADS", "usize"),
    ("kv_lora_rank", "KV_LORA_RANK", "usize"),
    ("qk_nope_head_dim", "QK_NOPE_HEAD_DIM", "usize"),
    ("qk_rope_head_dim", "QK_ROPE_HEAD_DIM", "usize"),
    ("v_head_dim", "V_HEAD_DIM", "usize"),
    ("vocab_size", "VOCAB_SIZE", "usize"),
    ("max_position_embeddings", "MAX_POSITION_EMBEDDINGS", "usize"),
    ("original_max_position_embeddings", "ROPE_ORIGINAL_MAX_POSITION_EMBEDDINGS", "usize"),
    ("rms_norm_eps", "RMS_NORM_EPS", "f32"),
    ("rope_theta", "ROPE_THETA", "f32"),
    ("factor", "ROPE_FACTOR", "f32"),
    ("beta_fast", "ROPE_BETA_FAST", "f32"),
    ("beta_slow", "ROPE_BETA_SLOW", "f32"),
    ("mscale", "ROPE_MSCALE", "f32"),
    ("mscale_all_dim", "ROPE_MSCALE_ALL_DIM", "f32"),
    ("routed_scaling_factor", "ROUTED_SCALING_FACTOR", "f32"),
    ("norm_topk_prob", "NORM_TOPK_PROB", "bool"),
];

fn value_after(json: &str, key: &str) -> Option<String> {
    let needle = format!("\"{key}\":");
    let start = json.find(&needle)? + needle.len();
    let rest = json[start..].trim_start();
    let end = rest.find(|c: char| c == ',' || c == '}' || c == '\n').unwrap_or(rest.len());
    Some(rest[..end].trim().to_string())
}

fn main() {
    let cfg = Path::new(&env::var("CARGO_MANIFEST_DIR").unwrap()).join("config.json");
    println!("cargo:rerun-if-changed={}", cfg.display());
    let json = fs::read_to_string(&cfg).unwrap();
    let mut out = String::from("// generated by build.rs from config.json — do not edit\n");
    for (key, name, ty) in KEYS {
        let v = value_after(&json, key).unwrap_or_else(|| panic!("config.json has no {key}"));
        let lit = match *ty {
            "usize" => v.parse::<u64>().unwrap_or_else(|_| panic!("{key}: {v}")).to_string(),
            "f32" => {
                v.parse::<f64>().unwrap_or_else(|_| panic!("{key}: {v}"));
                if v.contains(['.', 'e', 'E']) { v.clone() } else { format!("{v}.0") }
            }
            "bool" => { assert!(v == "true" || v == "false", "{key}: {v}"); v.clone() }
            _ => unreachable!(),
        };
        out.push_str(&format!("pub const {name}: {ty} = {lit};\n"));
    }
    fs::write(Path::new(&env::var("OUT_DIR").unwrap()).join("config_consts.rs"), out).unwrap();
}
