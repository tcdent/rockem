// Transcribes this directory's config.json into `$OUT_DIR/config_consts.rs`: the
// decoder's constants from `text_config`, the encoder's from `audio_config`, the
// splice's from the top level. A dumb copy: numbers are copied, never derived.
// Derived values live in src/lib.rs next to a comment saying how.
use std::{env, fs, path::Path};

const KEYS: &[(&str, &str, &str, &str)] = &[
    // (object, key, const, type); object "" is the top level
    ("", "audio_token_id", "AUDIO_TOKEN_ID", "usize"),
    ("text_config", "hidden_size", "HIDDEN_SIZE", "usize"),
    ("text_config", "intermediate_size", "INTERMEDIATE_SIZE", "usize"),
    ("text_config", "num_hidden_layers", "NUM_HIDDEN_LAYERS", "usize"),
    ("text_config", "num_attention_heads", "NUM_ATTENTION_HEADS", "usize"),
    ("text_config", "num_key_value_heads", "NUM_KEY_VALUE_HEADS", "usize"),
    ("text_config", "head_dim", "HEAD_DIM", "usize"),
    ("text_config", "vocab_size", "VOCAB_SIZE", "usize"),
    ("text_config", "rms_norm_eps", "RMS_NORM_EPS", "f32"),
    ("text_config", "rope_theta", "ROPE_THETA", "f32"),
    ("audio_config", "hidden_size", "ENC_HIDDEN_SIZE", "usize"),
    ("audio_config", "intermediate_size", "ENC_INTERMEDIATE_SIZE", "usize"),
    ("audio_config", "num_hidden_layers", "ENC_NUM_HIDDEN_LAYERS", "usize"),
    ("audio_config", "num_attention_heads", "ENC_NUM_ATTENTION_HEADS", "usize"),
    ("audio_config", "head_dim", "ENC_HEAD_DIM", "usize"),
    ("audio_config", "num_mel_bins", "NUM_MEL_BINS", "usize"),
    ("audio_config", "max_source_positions", "MAX_SOURCE_POSITIONS", "usize"),
];

/// The text of the JSON value (object or array) that follows `"key":`, brackets matched.
fn block<'a>(json: &'a str, key: &str) -> &'a str {
    let needle = format!("\"{key}\":");
    let start = json.find(&needle).unwrap_or_else(|| panic!("config.json has no {key}")) + needle.len();
    let rest = json[start..].trim_start();
    let (open, close) = if rest.starts_with('{') { ('{', '}') } else { ('[', ']') };
    let mut depth = 0;
    for (i, c) in rest.char_indices() {
        if c == open { depth += 1 }
        if c == close { depth -= 1; if depth == 0 { return &rest[..=i] } }
    }
    panic!("{key}: unbalanced")
}

fn value_after(json: &str, key: &str) -> String {
    let needle = format!("\"{key}\":");
    let start = json.find(&needle).unwrap_or_else(|| panic!("config.json has no {key}")) + needle.len();
    let rest = json[start..].trim_start();
    let end = rest.find(|c: char| c == ',' || c == '}' || c == '\n').unwrap_or(rest.len());
    rest[..end].trim().to_string()
}

fn main() {
    let cfg = Path::new(&env::var("CARGO_MANIFEST_DIR").unwrap()).join("config.json");
    println!("cargo:rerun-if-changed={}", cfg.display());
    let json = fs::read_to_string(&cfg).unwrap();
    let mut out = String::from("// generated by build.rs from config.json — do not edit\n");
    for (obj, key, name, ty) in KEYS {
        let scope = if obj.is_empty() { json.as_str() } else { block(&json, obj) };
        let v = value_after(scope, key);
        let lit = match *ty {
            "usize" => v.parse::<u64>().unwrap_or_else(|_| panic!("{key}: {v}")).to_string(),
            "f32" => {
                v.parse::<f64>().unwrap_or_else(|_| panic!("{key}: {v}"));
                if v.contains(['.', 'e', 'E']) { v.clone() } else { format!("{v}.0") }
            }
            _ => unreachable!(),
        };
        out.push_str(&format!("pub const {name}: {ty} = {lit};\n"));
    }
    fs::write(Path::new(&env::var("OUT_DIR").unwrap()).join("config_consts.rs"), out).unwrap();
}
